from datetime import datetime, timezone
from typing import Dict, Any, List


def generate_markdown_report(
    domain: str,
    dns_mail: Dict[str, Any],
    host_results: List[Dict[str, Any]]
) -> str:
    """
    Builds a structured Markdown scoping and posture report.
    """
    timestamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    live_hosts = [h for h in host_results if h["dns"]["resolvable"]]
    web_hosts = [h for h in host_results if h["http"]["reachable"]]

    lines = [
        f"# Attack Surface & Security Posture Report: `{domain}`",
        f"**Generated by:** ReconFlow v1.1.0  ",
        f"**Timestamp:** {timestamp}  ",
        "",
        "---",
        "",
        "## 1. Executive Summary",
        f"- **Total Discovered Subdomains (CT Logs):** {len(host_results)}",
        f"- **Active Resolvable Hosts (DNS):** {len(live_hosts)}",
        f"- **Reachable Web Services (HTTP/S):** {len(web_hosts)}",
        f"- **Domain Email Security Issues:** {len(dns_mail['issues'])}",
        "",
        "## 2. DNS & Email Spoofing Posture (SPF / DMARC)",
        f"- **MX Records:** {', '.join(dns_mail['mx_records']) if dns_mail['mx_records'] else 'None detected'}",
        f"- **SPF Record:** `{dns_mail['spf_record'] or 'Not Configured'}`",
        f"- **DMARC Record:** `{dns_mail['dmarc_record'] or 'Not Configured'}`",
        ""
    ]

    if dns_mail["issues"]:
        lines.append("### Identified DNS/Mail Findings:")
        for issue in dns_mail["issues"]:
            lines.append(f"- [!] {issue}")
    else:
        lines.append("- [OK] SPF and DMARC baseline policies are present.")

    lines.extend([
        "",
        "## 3. Active Asset Inventory & Web Posture",
        "",
        "| Subdomain | IP Address(es) | CNAME | HTTP Status | Server | TLS Expiry (Days) | Page Title |",
        "| :--- | :--- | :--- | :--- | :--- | :--- | :--- |"
    ])

    for item in host_results:
        sub = item["dns"]["hostname"]
        ips = ", ".join(item["dns"]["ips"][:2]) if item["dns"]["ips"] else "Unresolved"
        cname = item["dns"]["cname"] or "-"
        http = item["http"]

        if http["reachable"]:
            status = str(http["status_code"])
            server = http["server"]
            tls_days = str(http["tls_days_left"]) if http["tls_days_left"] is not None else "N/A"
            title = http["title"].replace("|", "-")
        else:
            status = "Unreachable"
            server = "-"
            tls_days = "-"
            title = "-"

        lines.append(f"| `{sub}` | {ips} | `{cname}` | {status} | {server} | {tls_days} | {title} |")

    lines.extend([
        "",
        "## 4. Web Security Header Audit",
        ""
    ])

    if not web_hosts:
        lines.append("_No active HTTP/HTTPS services responded during probing._")
    else:
        for item in web_hosts:
            sub = item["dns"]["hostname"]
            missing = item["http"]["missing_headers"]
            url = item["http"]["url"]
            lines.append(f"### `{sub}` ({url})")
            if missing:
                lines.append(f"- **Missing Headers ({len(missing)}):** `{', '.join(missing)}`")
            else:
                lines.append("- **Status:** All core defensive headers present.")
            lines.append("")

    lines.extend([
        "## 5. Remediation Guidance",
        "1. **Enforce HTTP Security Headers:** Configure web servers or reverse proxies (Nginx/Cloudflare/Apache) to emit `Strict-Transport-Security`, `Content-Security-Policy`, `X-Content-Type-Options: nosniff`, and `X-Frame-Options: DENY`.",
        "2. **Review Dangling CNAMEs:** Verify that any subdomain with an external `CNAME` record still points to an active, claimed third-party service to prevent subdomain takeover.",
        "3. **Harden Email Authentication:** Ensure SPF ends with `-all` or `~all` and configure DMARC with `p=quarantine` or `p=reject` once legitimate mail flows are verified.",
        ""
    ])

    return "\n".join(lines)
